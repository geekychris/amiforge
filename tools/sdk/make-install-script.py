#!/usr/bin/env python3
"""Generate an AmigaDOS script that installs the chosen AmigaOS 4.1 SDK components the way
the SDK's own installer would (package.xml), without its GUI.

    make-install-script.py SDK_Install/package.xml ARCHIVE_DIR DEST > install-sdk
"""
import sys
import xml.etree.ElementTree as ET

WANT = [
    "Base Installation", "GCC 11", "GCC Architecture Independent",
    "newlib Headers and Libraries", "ExecSG SDK", "POSIX Threads",
    "Contributions: abc-shell", "Contributions: coreutils", "Contributions: sed",
    "Contributions: grep", "Contributions: awk", "Contributions: diffutils",
    "Contributions: m4", "Contributions: flex", "Contributions: yacc",
    "Contributions: SDI Headers", "Contributions: pkgconfig", "Set file permissions for sh",
]

def lines(e):
    return [l.strip() for l in (e.text or "").splitlines() if l.strip()] if e is not None else []

pkg, arcdir, dest = sys.argv[1:4]
root = ET.parse(pkg).getroot()
out = ["; Installs the AmigaOS 4.1 SDK (generated by make-install-script.py)",
       "FailAt 21", f"MakeDir {dest} ALL >NIL:", f"Assign SDK: {dest}", "CD SDK:"]
done = set()
for o in root.findall("option"):
    name = o.get("name")
    if name not in WANT or name in done:
        continue
    done.add(name)
    out.append(f'Echo "== {name}"')
    out += lines(o.find("preinstall"))
    for f in o.findall("file"):
        out.append(f"xadUnFile {arcdir}/{f.text} DEST=SDK: OVERWRITE QUIET")
    out += lines(o.find("postinstall"))
    out.append("CD SDK:")
out += lines(root.find("postinstall"))
print("\n".join(l.replace("@(installpath)", dest) for l in out))
